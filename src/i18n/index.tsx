const DICTS: Record<LangCode, Dict> = { fr, en, pt, ar, yo };

type Ctx = { lang: LangCode; setLang: (l: LangCode) => void; t: (k: string) => string };
const LanguageContext = createContext<Ctx>({ lang: "fr", setLang: () => {}, t: (k) => k });

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [lang, setLangState] = useState<LangCode>(() => {
    const saved = localStorage.getItem("m4w-lang");
    return (LANGUAGES.some((l) => l.code === saved) ? saved : "fr") as LangCode;
  });

  useEffect(() => {
    localStorage.setItem("m4w-lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const value = useMemo<Ctx>(
    () => ({
      lang,
      setLang: setLangState,
      t: (k: string) => DICTS[lang][k] ?? fr[k] ?? k,
    }),
    [lang]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = () => useContext(LanguageContext);
export const useT = () => useContext(LanguageContext).t;
